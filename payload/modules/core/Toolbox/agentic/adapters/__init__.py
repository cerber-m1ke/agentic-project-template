"""Agent adapters: canonical .agents/ sources -> per-agent files.

An adapter is `.agents/adapters/<name>/adapter.toml` (data) plus an optional renderer module
`adapters/<name>.py` exposing `render(ctx: Context) -> dict[str, str]` (path relative to the
project root -> file content). Links (skills) are described in the toml and created by agents.py.
"""

from __future__ import annotations

import importlib
import json
import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType
from typing import Any

import tomli_w

import common

ADAPTERS_DIR = ".agents/adapters"
SKILLS_DIR = ".agents/skills"
SUBAGENTS_DIR = ".agents/agents"
HOOKS_FILE = ".agents/hooks/hooks.toml"
MCP_FILE = ".agents/mcp.toml"

GENERATED_NOTE = "generated by Toolbox/tb agents link — edit .agents/ instead"

EVENTS = ("session-start", "prompt-submit", "before-tool", "after-tool", "stop")
MODEL_TIERS = ("fast", "balanced", "strong")
TOOL_TIERS = ("read-only", "shell", "edit")
# Manifest sections whose `target` is a directory (not a generated file).
DIR_SECTIONS = ("skills", "subagents")

_NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


@dataclass
class Subagent:
    name: str
    description: str
    model: str | None      # fast | balanced | strong | None (agent default)
    tools: str             # read-only | shell | edit
    prompt: str            # body of the canonical file = system prompt
    source: str            # path relative to the project root


@dataclass
class Hook:
    name: str
    event: str
    description: str = ""


@dataclass
class McpServer:
    name: str
    transport: str                     # stdio | http
    command: str = ""
    args: list[str] = field(default_factory=list)
    env: dict[str, str] = field(default_factory=dict)
    url: str = ""
    headers: dict[str, str] = field(default_factory=dict)


@dataclass
class Context:
    root: Path
    agent: str                         # adapter name
    manifest: dict[str, Any]
    skills: list[str]
    subagents: list[Subagent]
    hooks: list[Hook]
    mcp_servers: list[McpServer]
    warnings: list[str] = field(default_factory=list)

    def section(self, name: str) -> dict[str, Any]:
        value = self.manifest.get(name)
        return value if isinstance(value, dict) else {}


# --- discovery ---------------------------------------------------------------------

def discover(root: Path) -> dict[str, dict[str, Any]]:
    """Adapters available in the project: name (directory) -> manifest. Broken ones are skipped."""
    base = root / ADAPTERS_DIR
    found: dict[str, dict[str, Any]] = {}
    if not base.is_dir():
        return found
    for path in sorted(base.glob("*/adapter.toml")):
        name = path.parent.name
        try:
            manifest = common.load_toml(path)
        except (OSError, ValueError) as exc:
            common.warn(f"{common.rel(path)}: {exc}")
            continue
        if manifest.get("name", name) != name:
            common.warn(f"{common.rel(path)}: name = {manifest.get('name')!r} differs from "
                        f"its directory; using {name!r}")
        manifest["name"] = name
        found[name] = manifest
    return found


def load_renderer(name: str, manifest: dict[str, Any]) -> ModuleType | None:
    module_name = str(manifest.get("renderer") or name).replace("-", "_")
    full = f"{__name__}.{module_name}"
    try:
        return importlib.import_module(full)
    except ModuleNotFoundError as exc:
        if exc.name == full:
            return None
        raise


# --- canonical sources -----------------------------------------------------------------

def list_skills(root: Path) -> list[str]:
    base = root / SKILLS_DIR
    if not base.is_dir():
        return []
    return sorted(p.name for p in base.iterdir() if p.is_dir() and (p / "SKILL.md").is_file())


def _load_subagents(root: Path, warnings: list[str]) -> list[Subagent]:
    base = root / SUBAGENTS_DIR
    result: list[Subagent] = []
    if not base.is_dir():
        return result
    for path in sorted(base.glob("*.md")):
        if path.name.lower() == "readme.md":
            continue
        where = common.rel(path)
        meta, body, error = common.read_note(path)
        if error or meta is None:
            warnings.append(f"{where}: {error or 'no YAML frontmatter'}; skipped")
            continue
        name = str(meta.get("name") or path.stem)
        if not _NAME_RE.match(name):
            warnings.append(f"{where}: invalid name {name!r} (use kebab-case); skipped")
            continue
        model = meta.get("model")
        if model is not None and model not in MODEL_TIERS:
            warnings.append(f"{where}: unknown model tier {model!r} (expected "
                            f"{' | '.join(MODEL_TIERS)}); agent default used")
            model = None
        tools = meta.get("tools", "read-only")
        if tools not in TOOL_TIERS:
            warnings.append(f"{where}: unknown tools tier {tools!r} (expected "
                            f"{' | '.join(TOOL_TIERS)}); read-only used")
            tools = "read-only"
        description = " ".join(str(meta.get("description") or "").split())
        if not description:
            warnings.append(f"{where}: empty description")
        result.append(Subagent(name=name, description=description, model=model, tools=tools,
                               prompt=body.strip() + "\n", source=where))
    return result


def _load_hooks(root: Path, warnings: list[str]) -> list[Hook]:
    path = root / HOOKS_FILE
    if not path.is_file():
        return []
    try:
        data = common.load_toml(path)
    except (OSError, ValueError) as exc:
        warnings.append(f"{HOOKS_FILE}: {exc}; hooks skipped")
        return []
    result: list[Hook] = []
    for i, item in enumerate(data.get("hook", []), 1):
        name, event = str(item.get("name", "")), str(item.get("event", ""))
        if not _NAME_RE.match(name):
            warnings.append(f"{HOOKS_FILE}: hook #{i}: invalid name {name!r}; skipped")
            continue
        if event not in EVENTS:
            warnings.append(f"{HOOKS_FILE}: hook {name!r}: unknown event {event!r} "
                            f"(expected {' | '.join(EVENTS)}); skipped")
            continue
        result.append(Hook(name=name, event=event, description=str(item.get("description", ""))))
    return result


def _str_map(value: Any) -> dict[str, str]:
    return {str(k): str(v) for k, v in sorted(value.items())} if isinstance(value, dict) else {}


def _load_mcp(root: Path, warnings: list[str]) -> list[McpServer]:
    path = root / MCP_FILE
    if not path.is_file():
        return []
    try:
        data = common.load_toml(path)
    except (OSError, ValueError) as exc:
        warnings.append(f"{MCP_FILE}: {exc}; MCP servers skipped")
        return []
    result: list[McpServer] = []
    for name, spec in sorted(data.get("servers", {}).items()):
        if not isinstance(spec, dict):
            continue
        command, url = spec.get("command"), spec.get("url")
        if bool(command) == bool(url):
            warnings.append(f"{MCP_FILE}: server {name!r} needs exactly one of `command` (stdio) "
                            "or `url` (http); skipped")
            continue
        if command:
            args = spec.get("args", [])
            result.append(McpServer(name=name, transport="stdio", command=str(command),
                                    args=[str(a) for a in args] if isinstance(args, list) else [],
                                    env=_str_map(spec.get("env"))))
        else:
            result.append(McpServer(name=name, transport="http", url=str(url),
                                    headers=_str_map(spec.get("headers"))))
    return result


def load_context(root: Path, name: str, manifest: dict[str, Any]) -> Context:
    warnings: list[str] = []
    return Context(root=root, agent=name, manifest=manifest, skills=list_skills(root),
                   subagents=_load_subagents(root, warnings), hooks=_load_hooks(root, warnings),
                   mcp_servers=_load_mcp(root, warnings), warnings=warnings)


def render(ctx: Context) -> dict[str, str]:
    renderer = load_renderer(ctx.agent, ctx.manifest)
    return dict(sorted(renderer.render(ctx).items())) if renderer else {}


# --- ownership of generated files ---------------------------------------------------------

def fixed_targets(manifest: dict[str, Any]) -> list[str]:
    """Generated files at fixed paths (`target` of every section except directory ones)."""
    targets = {
        str(section["target"]) for key, section in manifest.items()
        if isinstance(section, dict) and section.get("target") and key not in DIR_SECTIONS
    }
    return sorted(targets)


def has_generated_note(path: Path) -> bool:
    try:
        return GENERATED_NOTE in common.read_text(path)[:1000]
    except (OSError, UnicodeDecodeError):
        return False


def owned_files(root: Path, manifest: dict[str, Any], recorded: Any = ()) -> list[str]:
    """Paths this adapter may have generated: existing fixed targets, files in the subagents dir
    that carry the generated note, and paths of either kind recorded in local.toml [generated]
    (even if gone). Whether a file may actually be replaced is decided by its recorded hash."""
    fixed = fixed_targets(manifest)
    found = {t for t in fixed if (root / t).is_file() or t in recorded}
    target = manifest.get("subagents", {}).get("target")
    if target:
        prefix = f"{str(target).rstrip('/')}/"
        found |= {p for p in recorded if p.startswith(prefix) and "/" not in p[len(prefix):]}
        folder = root / target
        if folder.is_dir() and not common.is_link(folder):
            for path in folder.iterdir():
                if path.is_file() and not path.is_symlink() and has_generated_note(path):
                    found.add(f"{prefix}{path.name}")
    return sorted(found)


# --- helpers for renderers ------------------------------------------------------------------

def dump_json(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def dump_toml(obj: dict[str, Any], multiline: bool = False) -> str:
    return f"# {GENERATED_NOTE}\n\n" + tomli_w.dumps(obj, multiline_strings=multiline)


# POSIX sh: find the project root upwards from the cwd (the folder with the lock) and run its tb
# with the remaining arguments; outside a project it does nothing. $0 is "tb".
TB_FIND = ("sh -c 'd=$PWD; while [ ! -f \"$d/.agents/agentic.lock\" ]; do "
           "[ \"$d\" = / ] && exit 0; d=$(dirname \"$d\"); done; "
           "exec sh \"$d/Toolbox/tb\" \"$@\"' tb")


def hook_command(template: str, hook: Hook, ctx: Context) -> str:
    """Fill a command template: {name}, {agent}, {tb_find} (portable: finds the project root from
    the cwd), {tb} (absolute, shell-quoted Toolbox/tb), {tb_cmd} (relative, unquoted
    `Toolbox\\tb.cmd`: valid in both cmd and PowerShell when the hook runs from the project root;
    a quoted absolute path is a parse error in PowerShell)."""
    tb = shlex.quote((ctx.root / "Toolbox" / "tb").as_posix())
    return (template.replace("{name}", hook.name).replace("{agent}", ctx.agent)
            .replace("{tb_find}", TB_FIND).replace("{tb_cmd}", "Toolbox\\tb.cmd").replace("{tb}", tb))


def hooks_by_event(ctx: Context) -> dict[str, list[Hook]]:
    """Canonical hooks grouped by the agent's native event name (unsupported ones -> warning)."""
    events = ctx.section("hooks").get("events", {})
    grouped: dict[str, list[Hook]] = {}
    for hook in ctx.hooks:
        native = events.get(hook.event)
        if not native:
            ctx.warnings.append(f"hook {hook.name!r}: event {hook.event!r} is not supported by "
                                f"{ctx.agent}; skipped")
            continue
        grouped.setdefault(native, []).append(hook)
    return dict(sorted(grouped.items()))


def tier_value(ctx: Context, section: str, key: str, tier: str | None, what: str) -> str | None:
    """Look up a tier in a manifest map, e.g. [subagents] models = {fast = "haiku"}."""
    if tier is None:
        return None
    value = ctx.section(section).get(key, {}).get(tier)
    if value is None:
        ctx.warnings.append(f"[{section}] {key} has no entry for {what} {tier!r}")
    return value
