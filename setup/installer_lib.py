"""Shared installer logic for setup/init.py and setup/update.py.

Self-contained on purpose: it runs from the template repository (or from a fetched copy of it in
<project>/Runtime/update/<v>/) before or outside the project's Toolbox, so it must not import
anything from payload/. Dependencies: stdlib + tomli-w.
"""

from __future__ import annotations

import hashlib
import importlib.util
import os
import re
import shutil
import stat
import subprocess
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit, urlunsplit

import tomli_w

LANGS = ("ru", "en")
CLASSES = ("managed", "seeded", "block")
LOCK_PATH = ".agents/agentic.lock"
LOCK_HEADER = "# Generated by agentic-project-template. Do not edit by hand.\n"
LOCK_SCHEMA = 1
MODULES_DIR = "payload/modules"
PROFILES_DIR = "setup/profiles"
MIGRATIONS_DIR = "setup/migrations"
VERSION_FILE = "setup/VERSION"

LANG_RE = re.compile(r"^(?P<base>.+)\.(?P<lang>ru|en)(?P<ext>\.[A-Za-z0-9]+)?$")
# Release "X.Y.Z" or development state "X.Y.Z-dev" (the next release, not published yet).
VERSION_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)(-dev)?$")
MIGRATION_RE = re.compile(r"^(?P<version>\d+\.\d+\.\d+)_(?P<slug>[A-Za-z0-9][A-Za-z0-9_-]*)\.py$")
# A marker is a whole line: `<!-- agentic:begin -->` (Markdown) or `# agentic:begin` (git/ignore files).
# Prose that merely mentions the marker words never counts.
MARKER_RE = {kind: re.compile(rf"^\s*(?:<!--\s*agentic:{kind}\s*-->|#\s*agentic:{kind})\s*$")
             for kind in ("begin", "end")}
PLACEHOLDER_RE = re.compile(r"\{\{agentic\.([A-Za-z0-9_]+)\}\}")
PLACEHOLDER_KEYS = ("project_name", "language", "profile", "date", "profile_rules")
SKIP_NAMES = frozenset({"__pycache__", ".DS_Store", "Thumbs.db", "desktop.ini"})
SKIP_SUFFIXES = (".pyc", ".pyo")
# Without git (an unpacked archive) payload files come from a directory walk that also skips these
# folders: editor and Obsidian state, and the Runtime/ that tb puts next to its Toolbox.
WALK_SKIP_DIRS = frozenset({".git", ".idea", ".vscode", ".obsidian", ".trash", "__MACOSX"})
WALK_SKIP_TOP_DIRS = frozenset({"Runtime"})
CRLF_SUFFIXES = frozenset({".cmd", ".bat"})  # mirrors the project's .gitattributes

# Sentinels returned by local_hash() besides a sha256 hex digest.
NO_MARKERS = "<no-markers>"
NOT_A_FILE = "<not-a-file>"


class InstallerError(Exception):
    """User-facing error; callers print it as `error: <message>`."""


# --- small utilities -------------------------------------------------------------

def load_toml(path: Path) -> dict:
    try:
        with open(path, "rb") as fh:
            return tomllib.load(fh)
    except tomllib.TOMLDecodeError as exc:
        raise InstallerError(f"{path}: invalid TOML: {exc}") from exc


def parse_version(text: str) -> tuple[int, int, int, int]:
    """(major, minor, patch, release): X.Y.Z-dev sorts before X.Y.Z (release = 0 vs 1)."""
    m = VERSION_RE.match(text.strip())
    if not m:
        raise InstallerError(f"invalid version '{text.strip()}' (expected X.Y.Z or X.Y.Z-dev)")
    return int(m.group(1)), int(m.group(2)), int(m.group(3)), 0 if m.group(4) else 1


def is_release(version: str) -> bool:
    return parse_version(version)[3] == 1


def read_version(template_root: Path) -> str:
    path = template_root / VERSION_FILE
    if not path.is_file():
        raise InstallerError(f"{VERSION_FILE} not found in {template_root}")
    version = path.read_text(encoding="utf-8").strip()
    parse_version(version)
    return version


def posix(path: str) -> str:
    """Normalize a user-supplied relative path to the lock's form (forward slashes, no ./)."""
    p = path.replace("\\", "/").strip()
    while p.startswith("./"):
        p = p[2:]
    return p.rstrip("/")


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n")


def is_text(data: bytes) -> bool:
    if b"\0" in data:
        return False
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


def hash_text(text: str) -> str:
    return hashlib.sha256(normalize_newlines(text).encode("utf-8")).hexdigest()


def hash_bytes(data: bytes) -> str:
    """sha256 of file content: UTF-8 text with CRLF normalized to LF, binary as raw bytes."""
    if is_text(data):
        return hash_text(data.decode("utf-8"))
    return hashlib.sha256(data).hexdigest()


# --- managed blocks ----------------------------------------------------------------

def _lines(text: str) -> list[str]:
    parts = text.split("\n")
    lines = [p + "\n" for p in parts[:-1]]
    if parts[-1]:
        lines.append(parts[-1])
    return lines


def split_block(text: str) -> tuple[str, str, str] | None:
    """Split into (head incl. begin marker line, block, tail from end marker line); None without markers."""
    lines = _lines(normalize_newlines(text))
    begin = next((i for i, line in enumerate(lines) if MARKER_RE["begin"].match(line)), None)
    if begin is None:
        return None
    end = next((j for j in range(begin + 1, len(lines)) if MARKER_RE["end"].match(lines[j])), None)
    if end is None:
        return None
    return "".join(lines[: begin + 1]), "".join(lines[begin + 1 : end]), "".join(lines[end:])


def replace_block(text: str, block: str) -> str | None:
    parts = split_block(text)
    if parts is None:
        return None
    return parts[0] + block + parts[2]


def append_block(text: str, template_text: str) -> str:
    """Append the template's whole marker section to a file that lost its markers."""
    parts = split_block(template_text)
    if parts is None:
        raise InstallerError("template block file has no markers")
    begin_line = _lines(parts[0])[-1]
    end_line = _lines(parts[2])[0]
    text = normalize_newlines(text)
    if text and not text.endswith("\n"):
        text += "\n"
    sep = "\n" if text else ""
    return text + sep + begin_line + parts[1] + end_line.rstrip("\n") + "\n"


def block_hash(text: str) -> str | None:
    parts = split_block(text)
    return None if parts is None else hash_text(parts[1])


def local_hash(path: Path, cls: str) -> str | None:
    """Lock-style hash of a project file: None if absent, NO_MARKERS for a block file without markers."""
    if not path.exists() and not path.is_symlink():
        return None
    if not path.is_file():
        return NOT_A_FILE
    data = path.read_bytes()
    if cls == "block":
        if not is_text(data):
            return NO_MARKERS
        digest = block_hash(data.decode("utf-8"))
        return NO_MARKERS if digest is None else digest
    return hash_bytes(data)


# --- modules and profiles ------------------------------------------------------------

@dataclass
class Module:
    name: str
    path: Path
    description: str = ""
    required: bool = False
    default: bool = True
    seeded: list[str] = field(default_factory=list)
    block: list[str] = field(default_factory=list)
    executable: list[str] = field(default_factory=list)
    post_install: list[list[str]] = field(default_factory=list)


def _str_list(value: Any, where: str) -> list[str]:
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise InstallerError(f"{where}: expected a list of strings")
    return [posix(v) for v in value]


def load_modules(template_root: Path) -> dict[str, Module]:
    base = template_root / MODULES_DIR
    if not base.is_dir():
        raise InstallerError(f"{MODULES_DIR}/ not found in {template_root}")
    modules: dict[str, Module] = {}
    for d in sorted(base.iterdir()):
        if not d.is_dir() or d.name in SKIP_NAMES or d.name.startswith("."):
            continue
        manifest = d / "module.toml"
        where = f"{MODULES_DIR}/{d.name}/module.toml"
        if not manifest.is_file():
            raise InstallerError(f"{where} is missing")
        data = load_toml(manifest)
        if data.get("name", d.name) != d.name:
            raise InstallerError(f"{where}: name '{data.get('name')}' does not match the folder name")
        post = data.get("post_install", [])
        if not isinstance(post, list) or not all(
            isinstance(cmd, list) and cmd and all(isinstance(a, str) for a in cmd) for cmd in post
        ):
            raise InstallerError(f"{where}: post_install must be a list of argv lists")
        modules[d.name] = Module(
            name=d.name,
            path=d,
            description=str(data.get("description", "")),
            required=bool(data.get("required", False)),
            default=bool(data.get("default", True)),
            seeded=_str_list(data.get("seeded", []), f"{where}: seeded"),
            block=_str_list(data.get("block", []), f"{where}: block"),
            executable=_str_list(data.get("executable", []), f"{where}: executable"),
            post_install=[list(cmd) for cmd in post],
        )
    if "core" not in modules:
        raise InstallerError(f"{MODULES_DIR}/core is missing")
    return modules


def list_profiles(template_root: Path) -> list[str]:
    base = template_root / PROFILES_DIR
    return sorted(p.stem for p in base.glob("*.toml")) if base.is_dir() else []


def load_profile(template_root: Path, name: str) -> dict:
    available = list_profiles(template_root)
    if name not in available:
        raise InstallerError(f"unknown profile '{name}' (available: {', '.join(available) or 'none'})")
    where = f"{PROFILES_DIR}/{name}.toml"
    data = load_toml(template_root / PROFILES_DIR / f"{name}.toml")
    if data.get("name", name) != name:
        raise InstallerError(f"{where}: name does not match the file name")
    data["modules"] = _str_list(data.get("modules", []), f"{where}: modules")
    data["optional"] = _str_list(data.get("optional", []), f"{where}: optional")
    return data


def resolve_modules(profile: dict, modules: dict[str, Module],
                    with_: list[str] | None = None, without: list[str] | None = None) -> list[str]:
    """Module list for a profile and --with/--without overrides, in a stable order."""
    with_, without = list(with_ or []), list(without or [])
    known = ", ".join(modules)
    for name in [*profile["modules"], *profile["optional"]]:
        if name not in modules:
            raise InstallerError(f"profile '{profile.get('name')}' references unknown module '{name}'")
    for name in [*with_, *without]:
        if name not in modules:
            raise InstallerError(f"unknown module '{name}' (available: {known})")
    both = sorted(set(with_) & set(without))
    if both:
        raise InstallerError(f"module(s) both included and excluded: {', '.join(both)}")
    for name in without:
        if modules[name].required:
            raise InstallerError(f"module '{name}' is required and cannot be excluded")
    order = [*profile["modules"], *profile["optional"], *with_]
    selected = set(profile["modules"]) | {m for m in profile["optional"] if modules[m].default} | set(with_)
    selected |= {m for m, mod in modules.items() if mod.required}
    selected -= set(without)
    required_first = [m for m, mod in modules.items() if mod.required and m not in order]
    result: list[str] = []
    for name in ["core", *required_first, *order, *sorted(modules)]:
        if name in selected and name not in result:
            result.append(name)
    return result


def available_profile_modules(profile: dict, modules: dict[str, Module]) -> list[str]:
    """Modules a fresh init of this profile would include by default."""
    return [m for m in [*profile["modules"], *profile["optional"]]
            if m in modules and (m in profile["modules"] or modules[m].default)]


# --- rendering -------------------------------------------------------------------------

@dataclass
class Context:
    project_name: str
    language: str
    profile: str
    date: str
    template_root: Path
    _rules: str | None = None

    def rules(self) -> str:
        if self._rules is None:
            path = self.template_root / PROFILES_DIR / f"{self.profile}.{self.language}.md"
            if not path.is_file():
                raise InstallerError(f"{PROFILES_DIR}/{path.name} not found (needed for {{{{agentic.profile_rules}}}})")
            text = normalize_newlines(path.read_text(encoding="utf-8")).strip()
            self._rules = render(text, self, f"{PROFILES_DIR}/{path.name}", allow_rules=False)
        return self._rules

    def value(self, key: str) -> str:
        if key == "profile_rules":
            return self.rules()
        return str(getattr(self, key))


def render(text: str, ctx: Context, where: str, allow_rules: bool = True) -> str:
    def substitute(m: re.Match) -> str:
        key = m.group(1)
        if key not in PLACEHOLDER_KEYS or (key == "profile_rules" and not allow_rules):
            raise InstallerError(f"{where}: unsupported placeholder {m.group(0)}")
        return ctx.value(key)

    return PLACEHOLDER_RE.sub(substitute, text)


# --- materialization ----------------------------------------------------------------------

def dest_name(name: str, lang: str) -> str | None:
    """Installed file name for the selected language; None if the file belongs to the other language."""
    m = LANG_RE.match(name)
    if not m:
        return name
    if m.group("lang") != lang:
        return None
    return m.group("base") + (m.group("ext") or "")


@dataclass
class Entry:
    path: str          # destination, relative to the project root, forward slashes
    data: bytes        # final content (text: rendered, LF newlines)
    cls: str           # managed | seeded | block
    module: str
    executable: bool
    source: str        # payload file relative to the template root
    text: bool
    uses_rules: bool = False  # content contains {{agentic.profile_rules}}

    @property
    def content(self) -> str:
        return self.data.decode("utf-8")

    @property
    def block(self) -> str:
        parts = split_block(self.content)
        assert parts is not None
        return parts[1]

    @property
    def sha256(self) -> str:
        """Hash stored in agentic.lock (block files: the managed block only)."""
        if self.cls == "block":
            return hash_text(self.block)
        return hash_bytes(self.data)

    def lock_record(self) -> dict:
        return {"class": self.cls, "module": self.module, "sha256": self.sha256}


def _git_payload_files(template_root: Path, module_path: Path) -> list[str] | None:
    """Files of a module that git does not ignore (tracked or new), relative to the module folder.

    None when the template is not a git work tree of its own (an unpacked archive): then the caller
    walks the folder. git never consults a parent repository here (has_own_git)."""
    if not has_own_git(template_root):
        return None
    rel_module = module_path.relative_to(template_root).as_posix()
    res = git("ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", rel_module,
              cwd=template_root)
    if res.returncode != 0:
        raise InstallerError(f"git ls-files failed in {template_root}: {(res.stderr or res.stdout).strip()}")
    files = []
    for path in res.stdout.split("\0"):
        if not path:
            continue
        rel = path[len(rel_module) + 1:]
        if (module_path / rel).is_file():  # tracked but deleted in the work tree: not a payload file
            files.append(rel)
    return sorted(files)


def _walk_payload_files(module_path: Path) -> list[str]:
    files = []
    for dirpath, dirnames, filenames in os.walk(module_path):
        top = Path(dirpath) == module_path
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_NAMES and d not in WALK_SKIP_DIRS
                             and not (top and d in WALK_SKIP_TOP_DIRS))
        rel_dir = Path(dirpath).relative_to(module_path)
        files.extend((rel_dir / fname).as_posix() for fname in filenames)
    return sorted(files)


def module_files(module: Module, lang: str, template_root: Path) -> list[tuple[str, Path]]:
    """(destination, source) of every payload file of a module for the language.

    In a git clone of the template the files are what git tracks or would track: files that git
    ignores (an editor's .idea/, Obsidian's .obsidian/, a Runtime/ made by tb without TB_ROOT) are
    not part of the template, and `git status` would not show them to the pristine-clone check."""
    listed = _git_payload_files(template_root, module.path)
    if listed is None:
        listed = _walk_payload_files(module.path)
    files: list[tuple[str, Path]] = []
    for rel in listed:
        rel_path = Path(rel)
        fname = rel_path.name
        if fname in SKIP_NAMES or fname.endswith(SKIP_SUFFIXES):
            continue
        if any(part in SKIP_NAMES for part in rel_path.parts[:-1]):
            continue
        if rel == "module.toml":
            continue
        dest = dest_name(fname, lang)
        if dest is None:
            continue
        files.append(((rel_path.parent / dest).as_posix(), module.path / rel_path))
    return files


def materialize(template_root: Path, module_names: list[str], modules: dict[str, Module],
                ctx: Context) -> dict[str, Entry]:
    """Destination file set of a project, in memory: path -> Entry."""
    entries: dict[str, Entry] = {}
    for name in module_names:
        mod = modules[name]
        produced: set[str] = set()
        for dest, src in module_files(mod, ctx.language, template_root):
            source = src.relative_to(template_root).as_posix()
            if dest in entries:
                other = entries[dest]
                raise InstallerError(
                    f"destination '{dest}' is produced twice: {other.source} and {source}")
            raw = src.read_bytes()
            text = is_text(raw)
            cls = "seeded" if dest in mod.seeded else "block" if dest in mod.block else "managed"
            uses_rules = False
            if text:
                raw_text = normalize_newlines(raw.decode("utf-8"))
                uses_rules = any(m.group(1) == "profile_rules" for m in PLACEHOLDER_RE.finditer(raw_text))
                data = render(raw_text, ctx, source).encode("utf-8")
            else:
                data = raw
            if cls == "block" and (not text or split_block(data.decode("utf-8")) is None):
                raise InstallerError(f"{source}: block file without agentic:begin / agentic:end markers")
            entries[dest] = Entry(dest, data, cls, name, dest in mod.executable, source, text, uses_rules)
            produced.add(dest)
        for kind in ("seeded", "block", "executable"):
            for listed in getattr(mod, kind):
                if listed not in produced:
                    raise InstallerError(
                        f"{MODULES_DIR}/{name}/module.toml: {kind} path '{listed}' has no payload file "
                        f"for language '{ctx.language}'")
    return entries


def available_agents(entries: dict[str, Entry]) -> list[str]:
    found = set()
    for path in entries:
        parts = path.split("/")
        if len(parts) == 4 and parts[:2] == [".agents", "adapters"] and parts[3] == "adapter.toml":
            found.add(parts[2])
    return sorted(found)


# --- writing files --------------------------------------------------------------------------

def eol_text(rel_path: str, text: str) -> str:
    text = normalize_newlines(text)
    if Path(rel_path).suffix.lower() in CRLF_SUFFIXES:
        return text.replace("\n", "\r\n")
    return text


def write_file(root: Path, rel_path: str, data: bytes, text: bool, executable: bool = False) -> None:
    path = root / rel_path
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink() or path.is_dir():
        remove_path(path)
    elif path.exists() and not os.access(path, os.W_OK):
        os.chmod(path, stat.S_IWRITE | stat.S_IREAD)
    if text:
        data = eol_text(rel_path, data.decode("utf-8")).encode("utf-8")
    path.write_bytes(data)
    if executable and os.name != "nt":
        mode = path.stat().st_mode
        path.chmod(mode | ((mode & 0o444) >> 2))


def write_entry(root: Path, entry: Entry) -> None:
    write_file(root, entry.path, entry.data, entry.text, entry.executable)


def remove_path(path: Path) -> None:
    path = Path(path)
    if path.is_symlink() or (hasattr(path, "is_junction") and path.is_junction()):
        try:
            path.unlink()
        except (IsADirectoryError, PermissionError):
            os.rmdir(path)
    elif path.is_dir():
        rmtree(path)
    elif path.exists():
        if not os.access(path, os.W_OK):
            os.chmod(path, stat.S_IWRITE | stat.S_IREAD)
        path.unlink()


def remove_file_and_empty_parents(root: Path, rel_path: str) -> None:
    path = root / rel_path
    remove_path(path)
    parent = path.parent
    root = root.resolve()
    while parent.resolve() != root and parent.is_dir() and not any(parent.iterdir()):
        parent.rmdir()
        parent = parent.parent


def rmtree(path: Path) -> None:
    """shutil.rmtree that also removes read-only files (git objects on Windows)."""

    def _onexc(func, p, exc):
        try:
            mode = os.stat(p, follow_symlinks=False).st_mode
            if stat.S_ISLNK(mode):
                raise exc
            os.chmod(p, stat.S_IMODE(mode) | stat.S_IWRITE)  # keep the other permission bits
        except OSError:
            raise exc from None
        func(p)

    if Path(path).exists():
        shutil.rmtree(path, onexc=_onexc)


# --- lock ---------------------------------------------------------------------------------

def read_lock(root: Path) -> dict | None:
    path = root / LOCK_PATH
    return load_toml(path) if path.is_file() else None


def lock_text(lock: dict) -> str:
    files = lock.get("files", {})
    ordered = dict(lock)
    ordered["files"] = {k: files[k] for k in sorted(files)}
    return LOCK_HEADER + tomli_w.dumps(ordered)


def write_lock(root: Path, lock: dict) -> None:
    write_file(root, LOCK_PATH, lock_text(lock).encode("utf-8"), text=True)


def make_lock(source: str, version: str, commit: str, project: dict, files: dict[str, dict]) -> dict:
    return {
        "schema": LOCK_SCHEMA,
        "template": {"source": source, "version": version, "commit": commit},
        "project": project,
        "files": files,
    }


# --- git -----------------------------------------------------------------------------------

def run(cmd: list[str], cwd: Path | None = None, env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, env=env, text=True, encoding="utf-8", errors="replace",
                          capture_output=True)


def git(*args: str, cwd: Path, env: dict | None = None) -> subprocess.CompletedProcess:
    return run(["git", *args], cwd=cwd, env=env)


def has_own_git(path: Path) -> bool:
    """True if `path` is the top of its own git work tree (never consult a parent repository)."""
    return (path / ".git").exists()


def sanitize_url(url: str) -> str:
    """Drop credentials from http(s) URLs before they are recorded in the lock."""
    url = url.strip()
    try:
        parts = urlsplit(url)
    except ValueError:
        return url
    if parts.scheme in ("http", "https") and "@" in parts.netloc:
        host = parts.netloc.rsplit("@", 1)[1]
        return urlunsplit((parts.scheme, host, parts.path, parts.query, parts.fragment))
    return url


def template_git_info(template_root: Path) -> tuple[str, str]:
    """(source URL from origin, HEAD commit); empty strings when unknown."""
    if not has_own_git(template_root):
        return "", ""
    origin = git("remote", "get-url", "origin", cwd=template_root)
    head = git("rev-parse", "HEAD", cwd=template_root)
    source = sanitize_url(origin.stdout.strip()) if origin.returncode == 0 else ""
    commit = head.stdout.strip() if head.returncode == 0 else ""
    return source, commit


def git_identity_problem(cwd: Path) -> str | None:
    """Message if a commit would fail for lack of user.name / user.email."""
    for key, env_names in (("user.name", ("GIT_AUTHOR_NAME", "GIT_COMMITTER_NAME")),
                           ("user.email", ("GIT_AUTHOR_EMAIL", "GIT_COMMITTER_EMAIL"))):
        if all(os.environ.get(n) for n in env_names):
            continue
        value = git("config", "--get", key, cwd=cwd)
        if value.returncode != 0 or not value.stdout.strip():
            return (f"git {key} is not configured; set it first, e.g. "
                    f"git config --global {key} \"{'Your Name' if key == 'user.name' else 'you@example.com'}\"")
    return None


# --- migrations ----------------------------------------------------------------------------

def list_migrations(template_root: Path, old: str, new: str) -> list[tuple[str, Path]]:
    """Migration scripts to run when going from `old` to `new`, ordered by version then name.

    A migration named X.Y.Z runs when old < X.Y.Z and new >= X.Y.Z-dev: a development state of
    the release already carries it, and a project initialized from a development state of X.Y.Z
    gets it again on the way to the release (migrations are idempotent)."""
    base = template_root / MIGRATIONS_DIR
    if not base.is_dir():
        return []
    low, high = parse_version(old), parse_version(new)
    found = []
    for path in sorted(base.glob("*.py")):
        m = MIGRATION_RE.match(path.name)
        if not m:
            raise InstallerError(f"{MIGRATIONS_DIR}/{path.name}: bad migration name (expected <x.y.z>_<slug>.py)")
        version = parse_version(m.group("version"))
        if low < version and version[:3] + (0,) <= high:
            found.append((version, path.name, m.group("version"), path))
    return [(v, p) for _ver, _name, v, p in sorted(found)]


def run_migration(path: Path, project_root: Path) -> None:
    spec = importlib.util.spec_from_file_location(f"agentic_migration_{path.stem.replace('.', '_')}", path)
    if spec is None or spec.loader is None:
        raise InstallerError(f"cannot load migration {path.name}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    migrate = getattr(module, "migrate", None)
    if not callable(migrate):
        raise InstallerError(f"migration {path.name} does not define migrate(root)")
    migrate(project_root)
